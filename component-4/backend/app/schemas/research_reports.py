# 3. MODULE CONVERGENCE RISK REPORT (SO5, FR10)
# ============================================================================

class IterationCycleSummary(BaseModel):
    """Summary of a single test-fix-retest iteration."""

    iteration_number: int
    defects_count: int
    status: str
    resolved_defects: int
    timestamp: datetime


class ModuleConvergenceRiskReport(BaseModel):
    """Proposal-aligned diagnostic signal assessing architectural risk from loop behavior."""

    report_id: str = Field(description="Unique report identifier")
    module_name: str = Field(description="Name of the software module under verification")
    verification_run_id: str = Field(description="Current verification run ID")
    submission_id: str = Field(description="Current code submission ID")
    total_iterations: int = Field(default=1, description="Number of feedback cycles executed")
    risk_level: ConvergenceRiskLevel = Field(
        default=ConvergenceRiskLevel.LOW,
        description="LOW (1 iter), MEDIUM (2-3 iters), HIGH (4+ iters), CRITICAL (unbounded / repeated drift)"
    )
    is_superficial_convergence: bool = Field(
        default=False,
        description="True if tests passed but coincided with detected assertion weakening"
    )
    escalation_required: bool = Field(
        default=False,
        description="True if module must be escalated to human reviewer rather than auto-approved"
    )
    escalation_reason: Optional[str] = Field(default=None)
    diagnostic_signals: List[str] = Field(default_factory=list, description="Architectural risk indicators")
    iteration_history: List[IterationCycleSummary] = Field(default_factory=list)
    issued_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


