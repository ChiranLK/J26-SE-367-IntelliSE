from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.schemas.common import (
    ConvergenceRiskLevel,
    DefectCategory,
    DefectSeverity,
    DeploymentReadinessStatus,
    TestResultStatus,
    TestType,
)
from app.schemas.test_result import TestResult


# ============================================================================
# 1. SPECIALIZED AGENT REPORT SCHEMAS (SO1, FR01, FR02)
# ============================================================================

class UnitTestReport(BaseModel):
    """Execution telemetry and results generated by the Unit Test Agent."""

    agent_id: str = Field(default="agent-unit-01", description="Identifier of the Unit Test Agent")
    total_tests: int = Field(default=0, description="Total unit tests executed")
    passed_tests: int = Field(default=0, description="Passed unit tests count")
    failed_tests: int = Field(default=0, description="Failed unit tests count")
    duration_ms: float = Field(default=0.0, description="Total duration of unit test execution in ms")
    test_results: List[TestResult] = Field(default_factory=list, description="Granular unit test results")
    functions_covered: List[str] = Field(default_factory=list, description="Target functions/methods verified")
    generated_test_count: int = Field(default=0, description="Number of autonomously generated unit tests")
    generated_test_code: Optional[str] = Field(default=None, description="Autonomously synthesized test suite code")
    meaningful_oracle_available: bool = Field(default=False, description="True if verified formal contract/spec was available")
    specification_source: Optional[str] = Field(default=None, description="Source of verified test specification (e.g. explicit_specification, submitted_docstring)")
    trust_status: Optional[str] = Field(default=None, description="Trust status: AUTHORITATIVE, UNVERIFIED_SUGGESTION, or NO_SPECIFICATION")
    generation_provenance: Optional[Dict[str, Any]] = Field(default=None, description="Metadata explaining contract derivation")
    status: str = Field(default="PASSED", description="Overall unit test status")
    authorization_reason: Optional[str] = Field(default=None, description="Why this category was or was not authorized")


class IntegrationTestReport(BaseModel):
    """Interaction verification results generated by the Integration Test Agent."""

    agent_id: str = Field(default="agent-integration-01", description="Identifier of Integration Test Agent")
    total_interactions: int = Field(default=0, description="Number of cross-module / API / DB seams verified")
    passed_interactions: int = Field(default=0, description="Passed interaction tests")
    failed_interactions: int = Field(default=0, description="Failed interaction tests")
    duration_ms: float = Field(default=0.0, description="Total duration of integration tests in ms")
    test_results: List[TestResult] = Field(default_factory=list, description="Granular integration test results")
    test_seams_verified: List[str] = Field(default_factory=list, description="Verified dependency injection/API boundaries")
    status: str = Field(default="PASSED", description="Overall integration test status")
    authorization_reason: Optional[str] = Field(default=None, description="Validated category and boundary evidence")


class PerformanceMetrics(BaseModel):
    """Statistical latency and throughput metrics measured by Performance Test Agent."""

    sample_size: int = Field(default=0, description="Number of workload iterations/requests executed")
    duration_ms: float = Field(default=0.0, description="Total benchmark run duration in ms")
    workload_duration_ms: float = Field(default=0.0, description="Directly measured workload execution duration excluding container initialization")
    container_startup_overhead_ms: float = Field(default=0.0, description="Container initialization and teardown overhead in ms")
    mean_latency_ms: float = Field(default=0.0, description="Arithmetic mean execution latency in ms")
    latency_p50_ms: Optional[float] = Field(default=None, description="50th percentile latency, when emitted by the workload")
    latency_p95_ms: float = Field(default=0.0, description="95th percentile latency in ms")
    latency_p99_ms: Optional[float] = Field(default=None, description="99th percentile latency, when emitted by the workload")
    max_latency_ms: Optional[float] = Field(default=None, description="Maximum execution latency, when emitted by the workload")
    throughput_rps: float = Field(default=0.0, description="Calculated throughput (operations/requests per second)")
    threshold_latency_ms: float = Field(default=500.0, description="Configured maximum allowable latency threshold")
    is_breached: bool = Field(default=False, description="Whether latency threshold was breached")


class PerformanceTestReport(BaseModel):
    """Empirical load and latency evaluation generated by Performance Test Agent."""

    agent_id: str = Field(default="agent-performance-01", description="Identifier of Performance Test Agent")
    metrics: PerformanceMetrics = Field(default_factory=PerformanceMetrics, description="Calculated latency and throughput")
    bottlenecks_detected: List[str] = Field(default_factory=list, description="Identified execution bottlenecks")
    test_results: List[TestResult] = Field(default_factory=list, description="Performance SLA test results")
    status: str = Field(default="PASSED", description="PASSED or FAILED based on threshold breaches")
    authorization_reason: Optional[str] = Field(default=None, description="Validated category/workload authorization evidence")
    embedded_assertion_status: str = Field(default="NOT_EVALUATED", description="Outcome of the embedded pytest workload assertion")
    pipeline_sla_status: str = Field(default="NOT_EVALUATED", description="Independent pipeline threshold verdict")
    embedded_metrics: Dict[str, Any] = Field(default_factory=dict, description="Measurements emitted by the embedded workload")


class MultiAgentCoordinationPlan(BaseModel):
    """Shared execution plan orchestrating Unit, Integration, and Performance agents."""

    plan_id: str = Field(description="Unique plan identifier")
    verification_run_id: str = Field(description="Associated verification run")
    assigned_agents: List[str] = Field(default_factory=lambda: ["unit", "integration", "performance"])
    test_seams: List[str] = Field(default_factory=list, description="Extracted mockable boundaries / entry points")
    nfr_latency_threshold_ms: float = Field(default=500.0, description="Target latency constraint from NFRs")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


