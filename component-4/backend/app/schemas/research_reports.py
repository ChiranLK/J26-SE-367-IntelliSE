# 2. SEMANTIC-DRIFT DETECTION SCHEMAS (FR07, NFR01)
# ============================================================================

class DriftDetail(BaseModel):
    """Specific assertion weakening or scope reduction detected between test revisions."""

    test_name: str = Field(description="Name of the affected test function")
    drift_type: str = Field(
        description="ASSERTION_WEAKENED, TEST_DELETED, EXPECTED_VALUE_MODIFIED, or UNAUTHORIZED_SUITE_REPLACEMENT"
    )
    severity: DefectSeverity = Field(default=DefectSeverity.HIGH)
    description: str = Field(description="Explanation of the detected semantic deviation")
    original_expression: Optional[str] = Field(default=None, description="Original strict assertion expression")
    candidate_expression: Optional[str] = Field(default=None, description="Candidate modified or weakened expression")
    line_number: Optional[int] = Field(default=None)


class SemanticDriftReport(BaseModel):
    """Audit evaluation asserting whether test suite integrity was preserved across revisions."""

    report_id: str = Field(description="Unique report ID")
    verification_run_id: str = Field(description="Associated verification run")
    has_drift: bool = Field(default=False, description="True if any assertion weakening or deletion was detected")
    drift_types: List[str] = Field(default_factory=list, description="Distinct drift categories identified")
    details: List[DriftDetail] = Field(default_factory=list, description="Granular drift findings")
    original_test_count: int = Field(default=0)
    candidate_test_count: int = Field(default=0)
    original_assertion_count: int = Field(default=0)
    candidate_assertion_count: int = Field(default=0)
    requires_human_validation: bool = Field(default=False, description="Blocks automatic convergence if True")
    analyzed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class TestSuiteDriftAnalysisRequest(BaseModel):
    """Payload to trigger semantic drift evaluation on candidate test code."""

    candidate_test_code: str = Field(description="Candidate test suite Python source to inspect")


