# 4. DEPLOYMENT READINESS REPORT (FR11, NFR01)
# ============================================================================

class ReadinessGatingCheck(BaseModel):
    """Individual safety gate item required for deployment authorization."""

    gate_name: str = Field(description="Name of the safety condition")
    status: str = Field(description="PASSED, FAILED, WARNING, or NOT_EXECUTED")
    required: bool = Field(default=True, description="Whether passing is mandatory for release")
    details: str = Field(description="Evaluation rationale and observed evidence")


class DeploymentReadinessReport(BaseModel):
    """Formal release authorization certificate for a verified module."""

    report_id: str = Field(description="Unique certificate identifier")
    module_name: str = Field(description="Target module / file")
    verification_run_id: str = Field(description="Associated run ID")
    readiness_status: DeploymentReadinessStatus = Field(
        default=DeploymentReadinessStatus.BLOCKED,
        description="READY, BLOCKED, or NEEDS_REVIEW"
    )
    is_ready_for_deployment: bool = Field(default=False)
    gating_checks: List[ReadinessGatingCheck] = Field(default_factory=list)
    blocking_reasons: List[str] = Field(default_factory=list)
    provenance_hash: str = Field(description="Cryptographic content hash of verified source code and test suite")
    issued_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    sign_off_authority: str = Field(default="INTELISE-Component4-VerificationEngine")


