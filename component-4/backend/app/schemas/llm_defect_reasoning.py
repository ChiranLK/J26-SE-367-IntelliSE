"""
INTELISE Component 4 — Phase 3C.1A: LLM Defect Reasoning Schemas.

Defines structured Pydantic schemas for evidence-grounded LLM defect reasoning,
strict output validation, AI contribution telemetry, and machine-readable repair guidance.
"""
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class SupportedDefectCategory(str, Enum):
    """Supported defect taxonomy categories aligned with Component 4 research objectives."""
    FUNCTIONAL_BUG = "functional_bug"
    SECURITY_VULNERABILITY = "security_vulnerability"
    PERFORMANCE_BOTTLENECK = "performance_bottleneck"
    REGRESSION = "regression"
    INTEGRATION_DEFECT = "integration_defect"
    SEMANTIC_DRIFT = "semantic_drift"
    NON_CONVERGENT_BY_DESIGN = "non_convergent_by_design"
    CLEAN_CONTROL = "clean_control"
    UNKNOWN = "unknown"


class InferenceStatus(str, Enum):
    """Inference execution state tracking."""
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"
    TIMEOUT = "TIMEOUT"
    FALLBACK = "FALLBACK"
    VALIDATION_REJECTED = "VALIDATION_REJECTED"
    DISABLED = "DISABLED"


class LLMReasoningInput(BaseModel):
    """
    Permitted evidence package provided to the LLMDefectReasoningAgent.
    CRITICAL CONSTRAINT: Strictly isolates detector from hidden benchmark ground-truth labels.
    """
    candidate_source_code: str = Field(description="Candidate code being verified")
    filename: str = Field(default="solution.py", description="Target filename")
    unit_test_failure_messages: List[str] = Field(default_factory=list, description="Pytest failure summaries")
    integration_test_failure_messages: List[str] = Field(default_factory=list, description="Integration test failures")
    performance_observations: Optional[Dict[str, Any]] = Field(default=None, description="Observed latency & throughput metrics")
    ast_security_findings: List[Dict[str, Any]] = Field(default_factory=list, description="Static AST security scanner findings")
    semantic_drift_evidence: Optional[Dict[str, Any]] = Field(default=None, description="Semantic drift report details if test modified")
    relevant_stack_traces: List[str] = Field(default_factory=list, description="Pytest traceback excerpts")
    evidence_catalog: Dict[str, str] = Field(
        default_factory=dict,
        description="Catalog mapping evidence_id (e.g. 'ev_test_1', 'ev_ast_sec_0') to empirical observation summary",
    )


class LLMDefectHypothesis(BaseModel):
    """
    Structured hypothesis generated by LLMDefectReasoningAgent.
    Enforces strict typing, range constraints, and evidence-grounding validation.
    """
    predicted_defect_category: str = Field(
        default="functional_bug",
        description="Taxonomy category: functional_bug, security_vulnerability, performance_bottleneck, regression, integration_defect, semantic_drift, non_convergent_by_design, clean_control, unknown",
    )
    suspected_file: str = Field(
        default="solution.py",
        description="Source file containing the suspected defect",
    )
    suspected_line: Optional[int] = Field(
        default=None,
        description="1-based line number inside candidate source code if localized, or None",
    )
    root_cause_explanation: str = Field(
        default="",
        description="Technical explanation grounded strictly in verified test failures or AST findings",
    )
    supporting_evidence_ids: List[str] = Field(
        default_factory=list,
        description="List of valid evidence IDs from the evidence catalog supporting this hypothesis",
    )
    repair_recommendation: str = Field(
        default="",
        description="High-level, evidence-grounded repair guidance for Component 3",
    )
    confidence: float = Field(
        default=0.5,
        ge=0.0,
        le=1.0,
        description="Self-reported model confidence estimate between 0.0 and 1.0 (uncalibrated)",
    )
    uncertainty_reason: Optional[str] = Field(
        default=None,
        description="Reason for low confidence or ambiguity when evidence is insufficient",
    )
    model_identifier: str = Field(
        default="qwen2.5-coder:3b",
        description="Exact model identifier that produced this hypothesis",
    )
    model_digest: Optional[str] = Field(
        default=None,
        description="SHA-256 digest or version hash of the active local model",
    )
    inference_status: InferenceStatus = Field(
        default=InferenceStatus.SUCCESS,
        description="Execution status of LLM reasoning",
    )
    inference_duration_ms: Optional[float] = Field(
        default=None,
        description="Measured inference latency in milliseconds",
    )
    prompt_eval_count: Optional[int] = Field(
        default=None,
        description="Number of prompt tokens evaluated by Ollama",
    )
    eval_count: Optional[int] = Field(
        default=None,
        description="Number of tokens generated by Ollama",
    )

    # Post-validation fields populated by verification reconciliation
    validated_evidence_ids: List[str] = Field(
        default_factory=list,
        description="Subset of supporting_evidence_ids confirmed to exist in empirical evidence catalog",
    )
    rejected_evidence_ids: List[str] = Field(
        default_factory=list,
        description="Hallucinated or invalid evidence IDs removed during schema validation",
    )
    reconciliation_action: Optional[str] = Field(
        default=None,
        description="Reconciliation action applied (e.g. LOCALIZATION_PROMOTED, CATEGORY_REFINED, RETAINED_DETERMINISTIC)",
    )

    @field_validator("predicted_defect_category", mode="before")
    @classmethod
    def normalize_category(cls, v: Any) -> str:
        if not v:
            return SupportedDefectCategory.UNKNOWN.value
        s = str(v).strip().lower()
        # Map common variations
        synonyms = {
            "functional": SupportedDefectCategory.FUNCTIONAL_BUG.value,
            "logic_bug": SupportedDefectCategory.FUNCTIONAL_BUG.value,
            "bug": SupportedDefectCategory.FUNCTIONAL_BUG.value,
            "security": SupportedDefectCategory.SECURITY_VULNERABILITY.value,
            "vulnerability": SupportedDefectCategory.SECURITY_VULNERABILITY.value,
            "cwe": SupportedDefectCategory.SECURITY_VULNERABILITY.value,
            "performance": SupportedDefectCategory.PERFORMANCE_BOTTLENECK.value,
            "bottleneck": SupportedDefectCategory.PERFORMANCE_BOTTLENECK.value,
            "latency": SupportedDefectCategory.PERFORMANCE_BOTTLENECK.value,
            "integration": SupportedDefectCategory.INTEGRATION_DEFECT.value,
            "interface": SupportedDefectCategory.INTEGRATION_DEFECT.value,
            "drift": SupportedDefectCategory.SEMANTIC_DRIFT.value,
            "clean": SupportedDefectCategory.CLEAN_CONTROL.value,
            "no_defect": SupportedDefectCategory.CLEAN_CONTROL.value,
        }
        if s in synonyms:
            return synonyms[s]
        valid_vals = {cat.value for cat in SupportedDefectCategory}
        if s in valid_vals:
            return s
        return SupportedDefectCategory.UNKNOWN.value


class AIContributionTelemetry(BaseModel):
    """
    Granular measurement instrumentation capturing the exact AI contribution
    versus deterministic baseline for a single verification run or benchmark evaluation.
    """
    evaluation_mode: str = Field(
        default="DETERMINISTIC_ONLY",
        description="Active verification mode: DETERMINISTIC_ONLY or LLM_ASSISTED",
    )
    llm_enabled: bool = Field(default=False, description="Whether LLM defect reasoning was active")
    actual_llm_invocation_count: int = Field(default=0, ge=0, description="Genuine network/process LLM calls initiated")
    successful_llm_response_count: int = Field(default=0, ge=0, description="LLM calls returning valid structured JSON")
    failed_llm_response_count: int = Field(default=0, ge=0, description="LLM calls that errored, timed out, or returned malformed data")
    model_identifier: str = Field(default="qwen2.5-coder:3b", description="Configured or executed model name")
    model_digest: Optional[str] = Field(default=None, description="Active model digest from Ollama runtime")
    inference_latency_ms: float = Field(default=0.0, ge=0.0, description="Total LLM reasoning duration in milliseconds")
    timeout_events: int = Field(default=0, ge=0, description="Count of requests that exceeded timeout")
    fallback_events: int = Field(default=0, ge=0, description="Count of fallback activations due to error or rejection")
    validated_llm_findings: int = Field(default=0, ge=0, description="Count of findings successfully grounded in evidence")
    rejected_llm_findings: int = Field(default=0, ge=0, description="Count of unsupported/hallucinated findings rejected")
    claims_checked: int = Field(default=0, ge=0, description="Total individual model claims evaluated")
    llm_changed_classification: bool = Field(default=False, description="Whether LLM modified the final defect category")
    llm_changed_localization: bool = Field(default=False, description="Whether LLM localized line where deterministic was missing/imprecise")
    llm_changed_repair_recommendation: bool = Field(default=False, description="Whether LLM supplied enriched repair advice")
    unsupported_claims_generated: int = Field(default=0, ge=0, description="Total unsupported or invalid claims generated by model")
    unsupported_claims_rejected: int = Field(default=0, ge=0, description="Unsupported claims rejected by reconciliation rules")
    unsupported_claims_accepted: int = Field(default=0, ge=0, description="Unsupported claims that escaped to final reports (must be 0)")
    user_visible_feedback_errors: int = Field(default=0, ge=0, description="User-visible or machine-feedback errors introduced by LLM")
    prompt_tokens: Optional[int] = Field(default=None, description="Number of prompt tokens evaluated by Ollama if reported")
    completion_tokens: Optional[int] = Field(default=None, description="Number of generated tokens if reported")
    reconciliation_log: List[str] = Field(default_factory=list, description="Step-by-step audit log of reconciliation decisions")
